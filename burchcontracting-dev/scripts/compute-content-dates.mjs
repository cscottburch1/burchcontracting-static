/**
 * One-off (re-run-by-hand) script: derives datePublished/dateModified per
 * page from real git history and writes them to src/data/content-dates.js.
 *
 * Why this isn't computed live at build time instead: the deploy workflow's
 * checkout (.github/workflows/deploy.yml, actions/checkout@v4) uses the
 * default shallow fetch-depth of 1 — only the tip commit is present in CI,
 * so a live `git log` there would see one commit for every file and print
 * today's date for both datePublished and dateModified on every single
 * build. Computing dates here, once, on a machine with full history, and
 * committing the result follows the same pattern this repo already uses for
 * LAST_UPDATED_ISO/DISPLAY in generate-services.mjs — a checked-in constant,
 * manually refreshed — just per-page instead of one sitewide value.
 *
 * Re-run this (`node scripts/compute-content-dates.mjs`) whenever a page's
 * real content changes and you want dateModified to reflect that. Running
 * it after a purely mechanical change (formatting, schema plumbing) is
 * harmless but not meaningful — dateModified is supposed to answer "when did
 * the substance change," not "when did a script last touch this file."
 *
 * For generated pages (service/service-area/faqs.html), dates are derived
 * from git history of the underlying *data* file (services.js, geo-aeo.js)
 * rather than the generated HTML output — the HTML's own git history is
 * mostly noise from re-running the generator (whitespace, header/footer
 * partial edits), whereas the data file's history is what actually tracks
 * when a given service's or city's content last changed.
 */
import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function gitDates(relPath) {
  try {
    const out = execFileSync('git', ['log', '--follow', '--format=%aI', '--', relPath], { cwd: root })
      .toString()
      .trim()
    if (!out) return null
    const commits = out.split('\n').filter(Boolean)
    return {
      datePublished: commits[commits.length - 1].slice(0, 10),
      dateModified: commits[0].slice(0, 10),
    }
  } catch {
    return null
  }
}

// Hand-authored pages: dates come straight from the HTML file's own history.
const HAND_AUTHORED = [
  'index.html', 'about.html', 'contact.html', 'projects.html', 'services.html',
  'calculator/ada-bath-shower.html', 'calculator/additions.html',
  'calculator/basement-finishing.html', 'calculator/bath-remodel.html',
  'calculator/covered-patios.html', 'calculator/decks.html',
  'calculator/estimate.html', 'calculator/garages.html',
  'calculator/kitchen-remodel.html', 'calculator/porch.html',
  'calculator/whole-home-remodel.html',
]

// Generated pages: dates come from the data file that drives them, keyed
// by the same id the generator uses (service.id / area.slug), falling back
// to the generator's own history if the file-level date lookup ever misses.
const DATA_FILE_SOURCES = [
  { dataFile: 'src/data/services.js', fallbackFile: 'scripts/generate-services.mjs' },
  { dataFile: 'src/data/geo-aeo.js', fallbackFile: 'scripts/generate-geo-aeo.mjs' },
]

const result = {}

for (const file of HAND_AUTHORED) {
  const dates = gitDates(file)
  if (dates) result[file] = dates
}

// One shared pair of dates for everything driven by each data file — git
// doesn't track per-object history inside a file, only per-file. This is a
// known simplification: it can't tell "the decks service changed today" from
// "the ADU service changed today" if they're both in services.js. Good
// enough for a sitewide freshness signal; not a substitute for a real CMS.
for (const { dataFile, fallbackFile } of DATA_FILE_SOURCES) {
  const dates = gitDates(dataFile) ?? gitDates(fallbackFile)
  if (dates) result[`__datafile__${dataFile}`] = dates
}

const header = `/**
 * Auto-generated by scripts/compute-content-dates.mjs — do not hand-edit.
 * Re-run that script to refresh after real content changes. See its header
 * comment for why these are checked in rather than computed at build time.
 * Generated: ${new Date().toISOString().slice(0, 10)}
 */
`

const body = `export const CONTENT_DATES = ${JSON.stringify(result, null, 2)}\n`

mkdirSync(resolve(root, 'src/data'), { recursive: true })
writeFileSync(resolve(root, 'src/data/content-dates.js'), header + body)
console.log(`Wrote src/data/content-dates.js with dates for ${Object.keys(result).length} entries.`)

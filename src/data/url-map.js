/** Public URL for a source file path, e.g. 'about.html' -> '/about'. */
export function pageUrl(file) {
  const rel = file.split('\\').join('/').replace(/^\.\//, '')
  const url = PAGE_URLS[rel]
  if (!url) throw new Error(`url-map: no public URL for "${rel}" — add it to PAGE_URLS`)
  return url
}

/** Absolute URL for a source file path, for canonical tags and JSON-LD. */
export function canonicalUrl(file) {
  const url = pageUrl(file)
  return url === '/' ? `${SITE_ORIGIN}/` : `${SITE_ORIGIN}${url}`
}

/** The restored URL for a link written in the old scheme, or null. */
export function movedUrl(href) {
  return MOVED_URLS[href] ?? null
}
